// One-off: connect to the RDS Postgres using Mike's ilc-lighting-app credentials,
// CREATE DATABASE ebisu (skip if exists), then write app/.env pointing at it.
//
// Usage:  node scripts/create-ebisu-db.mjs
//
// Reads:   ../../ilc-lighting-app/.env  (for DATABASE_URL)
// Writes:  ../.env                       (Ebisu connection string + Auth placeholders)

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import crypto from 'node:crypto';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const APP_DIR = path.resolve(__dirname, '..');
const MIKE_ENV = path.resolve(APP_DIR, '../../ilc-lighting-app/.env');
const EBISU_ENV = path.resolve(APP_DIR, '.env');

function parseEnv(text) {
	const out = {};
	for (const line of text.split(/\r?\n/)) {
		const m = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/);
		if (!m) continue;
		let v = m[2];
		if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
			v = v.slice(1, -1);
		}
		out[m[1]] = v;
	}
	return out;
}

function buildAdminUrl(originalUrl) {
	// Point at the `postgres` admin DB so we can CREATE DATABASE ebisu.
	const u = new URL(originalUrl);
	u.pathname = '/postgres';
	return u.toString();
}

function buildEbisuUrl(originalUrl) {
	const u = new URL(originalUrl);
	u.pathname = '/ebisu';
	return u.toString();
}

async function main() {
	const mikeEnvText = await fs.readFile(MIKE_ENV, 'utf8');
	const mikeEnv = parseEnv(mikeEnvText);
	if (!mikeEnv.DATABASE_URL) throw new Error('DATABASE_URL not found in Mike .env');

	const adminUrl = buildAdminUrl(mikeEnv.DATABASE_URL);
	const ebisuUrl = buildEbisuUrl(mikeEnv.DATABASE_URL);

	console.log('Connecting to RDS admin DB (postgres) to issue CREATE DATABASE…');
	const client = new pg.Client({ connectionString: adminUrl, ssl: { rejectUnauthorized: false } });
	await client.connect();

	const { rows } = await client.query("SELECT 1 FROM pg_database WHERE datname = 'ebisu'");
	if (rows.length > 0) {
		console.log('Database "ebisu" already exists. Skipping CREATE.');
	} else {
		await client.query('CREATE DATABASE ebisu');
		console.log('CREATE DATABASE ebisu — done.');
	}

	await client.end();

	// Write app/.env. Don't clobber an existing one.
	let existing = '';
	try {
		existing = await fs.readFile(EBISU_ENV, 'utf8');
	} catch {}
	if (existing.includes('DATABASE_URL=')) {
		console.log('app/.env already has DATABASE_URL — not overwriting.');
		return;
	}

	const authSecret = crypto.randomBytes(32).toString('base64');
	const env = [
		'# Generated by scripts/create-ebisu-db.mjs',
		'',
		`DATABASE_URL="${ebisuUrl}"`,
		'',
		`AUTH_SECRET="${authSecret}"`,
		'',
		'# Set these when you wire up Google OAuth (see plan).',
		'AUTH_GOOGLE_ID=""',
		'AUTH_GOOGLE_SECRET=""',
		'',
		'AUTH_ALLOWED_EMAIL_DOMAINS="ilcstudios.com"',
		''
	].join('\n');

	await fs.writeFile(EBISU_ENV, env, 'utf8');
	console.log(`Wrote ${EBISU_ENV}`);
}

main().catch((err) => {
	console.error('Failed:', err.message);
	process.exit(1);
});
